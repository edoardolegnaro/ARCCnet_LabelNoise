"""Train and evaluate one fold of the cutout benchmark."""

import json
import logging
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import pytorch_lightning as pl
import torch
from pytorch_lightning.callbacks import EarlyStopping, ModelCheckpoint
from pytorch_lightning.loggers import CSVLogger
from pytorch_lightning.tuner import Tuner
from sklearn.preprocessing import LabelEncoder
from sklearn.utils.class_weight import compute_class_weight

import arccnet_labelnoise.config as config
from arccnet.models import preprocessing_common as pp_common
from arccnet_labelnoise.data_preparation import (
    complete_fov_mask,
    prepare_dataset,
)
from arccnet_labelnoise.lightning_data import HaleDataModule
from arccnet_labelnoise.lightning_model import HaleLightningModel


class HaleTrainer:
    """Trainer class for Hale classification models."""

    WARNING_PATTERNS = [
        ".*hipBLASLt.*",  # AMD GPUs warning
        ".*Precision.*not supported by the model summary.*",
        ".*does not have many workers.*",
        ".*Please use the new API settings to control TF32 behavior.*",
        ".*You are using a CUDA device.*Tensor Cores.*",
    ]

    def __init__(self, class_names: list[str] | None = None):
        """Initialize the trainer."""
        self.class_names = class_names or config.class_names
        self._setup_warnings()
        self.seed = int(getattr(config, "RANDOM_STATE", 42))
        self._seed_everything(self.seed)
        self.precision = self._get_precision()

    def _setup_warnings(self) -> None:
        """Suppress common warnings."""
        for pattern in self.WARNING_PATTERNS:
            warnings.filterwarnings("ignore", category=UserWarning, message=pattern)

    def _get_precision(self) -> str:
        """Get mixed precision setting."""
        accelerator = str(getattr(config, "ACCELERATOR", "auto")).lower()
        use_mixed_precision = torch.cuda.is_available() and accelerator != "cpu"
        precision = "16-mixed" if use_mixed_precision else "32-true"
        logging.info(f"Using precision: {precision}")
        return precision

    def _seed_everything(self, seed: int) -> None:
        """Seed all RNGs used by Lightning/PyTorch for reproducibility."""
        pl.seed_everything(seed, workers=True)
        if hasattr(torch.backends, "cudnn"):
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
        try:
            torch.use_deterministic_algorithms(True, warn_only=True)
        except Exception:
            pass
        logging.info("Global seed set to %d", seed)

    def prepare_dataset_once(self) -> pd.DataFrame:
        """Prepare and encode the dataset once."""
        filename = config.PROCESSED_DATASET_FILENAME
        processed_data_path = Path(config.DATA_FOLDER) / filename

        if processed_data_path.exists():
            logging.info(f"Loading previously prepared dataset: {processed_data_path.name}")
            df_processed = pd.read_parquet(processed_data_path)
        else:
            logging.info("Preparing dataset for the first time...")
            df_processed = prepare_dataset(save_path=str(processed_data_path))

        if config.REQUIRE_COMPLETE_FOV:
            complete_mask = complete_fov_mask(df_processed)
            incomplete_count = int((~complete_mask).sum())
            if incomplete_count:
                raise ValueError(
                    f"Processed dataset {processed_data_path} contains {incomplete_count:,} incomplete "
                    "preferred-instrument cutouts. Use the spatial-policy-specific cache generated by "
                    "the current preparation pipeline."
                )

        instrument_filter = str(getattr(config, "INSTRUMENT_FILTER", "all")).lower()
        if instrument_filter != "all":
            # Same HMI-first preference as the image loader and complete_fov_mask.
            hmi_preferred = pp_common.availability_mask(df_processed, "path_image_cutout_hmi")
            keep = hmi_preferred if instrument_filter == "hmi" else ~hmi_preferred
            rows_before = len(df_processed)
            df_processed = df_processed.loc[keep].copy()
            logging.info(
                "Instrument filter %r retained %s/%s observations (fold assignments unchanged).",
                instrument_filter,
                len(df_processed),
                rows_before,
            )

        logging.info(f"Dataset shape: {df_processed.shape}")
        logging.info(f"Label distribution:\n{df_processed['grouped_labels'].value_counts()}")

        df_processed = self._encode_labels(df_processed)
        df_processed = self._encode_delta_labels(df_processed)
        return df_processed

    def _encode_labels(self, df: pd.DataFrame) -> pd.DataFrame:
        """Encode labels consistently."""
        logging.info("Creating consistent label encoding from 'grouped_labels'...")
        label_encoder = LabelEncoder()
        df["model_labels"] = label_encoder.fit_transform(df["grouped_labels"])

        label_mapping = {label: int(index) for index, label in enumerate(label_encoder.classes_)}
        logging.info(f"Label mapping: {label_mapping}")

        model_labels_dist = df["model_labels"].value_counts().sort_index().to_dict()
        logging.info(f"Model labels distribution: {model_labels_dist}")

        actual_classes = len(label_encoder.classes_)
        if actual_classes != config.NUM_CLASSES:
            logging.warning(
                f"Expected {config.NUM_CLASSES} classes but found {actual_classes}: {list(label_encoder.classes_)}"
            )
        else:
            logging.info(f"Found expected {actual_classes} classes: {list(label_encoder.classes_)}")

        return df

    def _encode_delta_labels(self, df: pd.DataFrame) -> pd.DataFrame:
        """Add binary delta-present labels from the original Hale label."""
        if "label" not in df.columns:
            logging.warning("No original 'label' column found; delta auxiliary labels default to 0.")
            df["delta_labels"] = 0
            return df
        df["delta_labels"] = df["label"].astype(str).str.contains("Delta", na=False).astype(int)
        logging.info("Delta labels distribution: %s", df["delta_labels"].value_counts().sort_index().to_dict())
        return df

    def train_single_fold(self, df: pd.DataFrame, fold_num: int = 1, parent_loggers: list | None = None) -> tuple:
        """Train model on a single fold."""
        logging.info(f"Training on fold {fold_num}")

        data_module = self._create_data_module(df, fold_num)
        model = self._create_model(data_module)
        loggers = self._setup_loggers(fold_num, parent_loggers)
        trainer = self._create_trainer(loggers, fold_num)
        self._run_lr_finder_if_requested(trainer, model, data_module, fold_num)
        trainer.fit(model, data_module)
        test_results = trainer.test(model, data_module, ckpt_path="best")
        self._evaluate_model(model, data_module, loggers, fold_num, test_results, trainer)

        return trainer, model, test_results

    def _create_data_module(self, df: pd.DataFrame, fold_num: int) -> HaleDataModule:
        """Create and setup data module."""
        data_module = HaleDataModule(df=df, fold_num=fold_num)
        data_module.setup("fit")

        return data_module

    def _create_model(self, data_module: HaleDataModule) -> HaleLightningModel:
        """Create model with the configured imbalance-loss policy."""
        train_labels = data_module.get_train_labels()
        train_delta_labels = data_module.train_dataset.df.get("delta_labels")
        unique_labels = np.unique(train_labels)
        num_classes = int(config.NUM_CLASSES)
        loss_policy = str(getattr(config, "LOSS_POLICY", "balanced_ce"))
        allowed_loss_policies = {"unweighted_ce", "balanced_ce", "sqrt_balanced_ce", "focal_loss"}
        if loss_policy not in allowed_loss_policies:
            raise ValueError(
                f"Unsupported Hale loss policy: {loss_policy}. Use one of {sorted(allowed_loss_policies)}."
            )

        class_weights_np: np.ndarray | None
        if loss_policy == "unweighted_ce":
            class_weights_np = None
        else:
            class_weights_np = np.ones(num_classes, dtype=np.float32)

            if unique_labels.size > 0:
                present_weights = compute_class_weight("balanced", classes=unique_labels, y=train_labels)
                class_weights_np[unique_labels.astype(int)] = present_weights.astype(np.float32)

            if loss_policy == "sqrt_balanced_ce":
                class_weights_np = np.sqrt(class_weights_np)

            missing_labels = sorted(set(range(num_classes)) - set(unique_labels.tolist()))
            if missing_labels:
                logging.warning(
                    "Training fold is missing classes %s. Assigning zero loss weight for those classes in this fold.",
                    missing_labels,
                )
                class_weights_np[missing_labels] = 0.0

        class_weights = torch.tensor(class_weights_np, dtype=torch.float32) if class_weights_np is not None else None
        delta_aux_weight = float(getattr(config, "DELTA_AUX_WEIGHT", 0.0))
        delta_aux_mask_alpha = bool(getattr(config, "DELTA_AUX_MASK_ALPHA", False))
        delta_pos_weight_power = float(getattr(config, "DELTA_POS_WEIGHT_POWER", 1.0))
        if not 0.0 <= delta_pos_weight_power <= 1.0:
            raise ValueError("DELTA_POS_WEIGHT_POWER must be between 0 and 1.")
        alpha_class_index = None
        delta_pos_weight = None
        if delta_aux_weight > 0.0 and train_delta_labels is not None:
            delta_weight_labels = np.asarray(train_delta_labels)
            if delta_aux_mask_alpha:
                if "Alpha" not in config.class_names:
                    raise ValueError("Delta auxiliary Alpha masking requires an 'Alpha' main class.")
                alpha_class_index = config.class_names.index("Alpha")
                eligible_mask = np.asarray(train_labels) != alpha_class_index
                delta_weight_labels = delta_weight_labels[eligible_mask]
                if delta_weight_labels.size == 0:
                    raise ValueError("No non-Alpha training samples are available for the delta auxiliary task.")

            positives = float(delta_weight_labels.sum())
            negatives = float(len(delta_weight_labels) - positives)
            if positives > 0.0:
                delta_pos_weight = torch.tensor(
                    [(negatives / positives) ** delta_pos_weight_power],
                    dtype=torch.float32,
                )
            logging.info(
                "Delta auxiliary head enabled: weight=%s, mask_alpha=%s, eligible=%s, "
                "positives=%s, negatives=%s, pos_weight_power=%s, pos_weight=%s",
                delta_aux_weight,
                delta_aux_mask_alpha,
                len(delta_weight_labels),
                int(positives),
                int(negatives),
                delta_pos_weight_power,
                delta_pos_weight,
            )

        logging.info("Loss policy: %s", loss_policy)
        logging.info("Class weights: %s", class_weights)

        model = HaleLightningModel(
            num_classes=config.NUM_CLASSES,
            learning_rate=config.LEARNING_RATE,
            model_name=config.MODEL_NAME,
            class_weights=class_weights,
            loss_policy=loss_policy,
            focal_loss_gamma=float(getattr(config, "FOCAL_LOSS_GAMMA", 2.0)),
            delta_aux_weight=delta_aux_weight,
            delta_pos_weight=delta_pos_weight,
            delta_aux_mask_alpha=delta_aux_mask_alpha,
            alpha_class_index=alpha_class_index,
            data_type=config.DATA_TYPE,
            input_size=config.IMAGE_TARGET_SIZE,
        )

        num_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
        logging.info(f"Model: {config.MODEL_NAME} with {config.NUM_CLASSES} classes")
        logging.info("Model input size: %s", config.IMAGE_TARGET_SIZE)
        logging.info(f"Total trainable parameters: {num_params:,}")

        return model

    def _setup_loggers(self, fold_num: int, parent_loggers: list | None) -> list:
        """Setup loggers for training."""
        if parent_loggers is not None:
            logging.info(f"Using parent loggers for fold {fold_num}")
            return parent_loggers

        return [CSVLogger(config.LOG_DIR, name=f"fold_{fold_num}")]

    def _create_trainer(self, loggers: list, fold_num: int = 1) -> pl.Trainer:
        """Create PyTorch Lightning trainer."""
        return pl.Trainer(
            max_epochs=config.MAX_EPOCHS,
            accelerator=config.ACCELERATOR,
            devices=config.DEVICES,
            precision=self.precision,
            logger=loggers,
            callbacks=self._create_callbacks(fold_num),
            gradient_clip_val=float(getattr(config, "GRADIENT_CLIP_VAL", 0.0)),
            log_every_n_steps=config.LOG_EVERY_N_STEPS,
            enable_progress_bar=True,
            enable_model_summary=getattr(config, "ENABLE_MODEL_SUMMARY", True),
            deterministic=True,
            benchmark=False,
        )

    def _create_callbacks(self, fold_num: int) -> list:
        """Create training callbacks."""
        checkpoint_monitor = getattr(config, "CHECKPOINT_MONITOR", "val_acc")
        checkpoint_callback = ModelCheckpoint(
            monitor=checkpoint_monitor,
            mode=getattr(config, "CHECKPOINT_MODE", "max"),
            save_top_k=1,
            filename=f"hale-fold{fold_num}-{{epoch:02d}}-{{{checkpoint_monitor}:.3f}}",
            dirpath=getattr(config, "LOG_DIR", "logs"),
        )

        early_stop_callback = EarlyStopping(
            monitor=config.EARLY_STOPPING_MONITOR,
            patience=config.EARLY_STOPPING_PATIENCE,
            mode=config.EARLY_STOPPING_MODE,
            verbose=True,
        )

        return [checkpoint_callback, early_stop_callback]

    def _run_lr_finder_if_requested(
        self,
        trainer: pl.Trainer,
        model: HaleLightningModel,
        data_module: HaleDataModule,
        fold_num: int,
    ) -> None:
        """Optionally run Lightning's LR finder before the actual fit."""
        if not getattr(config, "AUTO_LR_FIND", False):
            return

        output_dir = Path(getattr(config, "LOG_DIR", "logs"))
        output_dir.mkdir(parents=True, exist_ok=True)
        output_path = output_dir / f"fold_{fold_num}_lr_find.json"

        try:
            lr_finder = Tuner(trainer).lr_find(
                model,
                datamodule=data_module,
                min_lr=float(getattr(config, "LR_FIND_MIN_LR", 1e-7)),
                max_lr=float(getattr(config, "LR_FIND_MAX_LR", 1e-2)),
                num_training=int(getattr(config, "LR_FIND_NUM_TRAINING", 100)),
                update_attr=True,
                attr_name="learning_rate",
            )
            suggestion = lr_finder.suggestion() if lr_finder is not None else None
            payload = {
                "fold": fold_num,
                "suggested_lr": suggestion,
                "model_learning_rate": float(model.learning_rate),
                "min_lr": float(getattr(config, "LR_FIND_MIN_LR", 1e-7)),
                "max_lr": float(getattr(config, "LR_FIND_MAX_LR", 1e-2)),
                "num_training": int(getattr(config, "LR_FIND_NUM_TRAINING", 100)),
            }
            if lr_finder is not None:
                payload["results"] = {
                    key: [float(value) for value in values] for key, values in lr_finder.results.items()
                }
            with output_path.open("w", encoding="utf-8") as handle:
                json.dump(payload, handle, indent=2)
            logging.info("LR finder result for fold %s written to %s", fold_num, output_path)
        except Exception as exc:
            logging.warning("LR finder failed for fold %s; continuing with configured LR: %s", fold_num, exc)

    def _evaluate_model(
        self,
        model: HaleLightningModel,
        data_module: HaleDataModule,
        loggers: list,
        fold_num: int,
        test_results: list[dict],
        trainer: pl.Trainer,
    ) -> None:
        """Perform comprehensive model evaluation."""
        if not test_results:
            logging.warning("No test results available for evaluation")
            return

        test_metrics = test_results[0]

        self._save_evaluation_artifacts(
            model,
            data_module,
            fold_num,
            test_metrics,
            trainer.checkpoint_callback.best_model_path,
        )
        model.reset_test_collections()

    def _save_evaluation_artifacts(
        self,
        model: HaleLightningModel,
        data_module: HaleDataModule,
        fold_num: int,
        test_metrics: dict,
        best_model_path: str | None,
    ) -> None:
        """Save paper-facing fold evaluation artifacts as JSON/CSV files."""
        try:
            output_dir = Path(getattr(config, "LOG_DIR", "logs")) / f"fold_{fold_num}_evaluation"
            output_dir.mkdir(parents=True, exist_ok=True)

            cm, class_report = model.get_confusion_matrix_and_classification_report(self.class_names)
            metric_report = model.get_classification_metric_report(self.class_names)
            delta_metric_report = model.get_delta_metric_report()
            delta_routed_metric_report = model.get_delta_routed_metric_report()
            delta_predictions_path = self._save_delta_predictions(
                model,
                data_module,
                fold_num,
                output_dir,
            )
            try:
                test_predictions_path = self._save_test_predictions(model, data_module, fold_num, output_dir)
            except Exception as exc:
                logging.warning("Could not save fold %s test predictions: %s", fold_num, exc)
                test_predictions_path = None
            payload = {
                "fold": fold_num,
                "classes": config.classes,
                "class_names": list(self.class_names),
                "data_type": config.DATA_TYPE,
                "model_name": config.MODEL_NAME,
                "test_metrics": {
                    key: float(value) if isinstance(value, int | float) else value
                    for key, value in test_metrics.items()
                },
                "best_checkpoint": best_model_path,
                "confusion_matrix": cm.tolist() if cm is not None else None,
                "classification_report": class_report,
                "classification_metric_report": metric_report,
                "delta_metric_report": delta_metric_report,
                "delta_routed_metric_report": delta_routed_metric_report,
                "delta_predictions_csv": str(delta_predictions_path) if delta_predictions_path else None,
                "test_predictions_csv": str(test_predictions_path) if test_predictions_path else None,
            }

            with (output_dir / "evaluation.json").open("w", encoding="utf-8") as handle:
                json.dump(payload, handle, indent=2, default=str)

            if cm is not None:
                pd.DataFrame(cm, index=self.class_names, columns=self.class_names).to_csv(
                    output_dir / "confusion_matrix.csv"
                )

            if class_report:
                report_rows = []
                for label, metrics in class_report.items():
                    if isinstance(metrics, dict):
                        report_rows.append({"label": label, **metrics})
                    else:
                        report_rows.append({"label": label, "value": metrics})
                pd.DataFrame(report_rows).to_csv(output_dir / "classification_report.csv", index=False)

            logging.info("Fold %s evaluation artifacts written to: %s", fold_num, output_dir)
        except Exception as exc:
            logging.warning("Could not save fold %s evaluation artifacts: %s", fold_num, exc)

    def _save_test_predictions(
        self,
        model: HaleLightningModel,
        data_module: HaleDataModule,
        fold_num: int,
        output_dir: Path,
    ) -> Path | None:
        """Save held-out class probabilities aligned with the test metadata rows."""
        logits = getattr(model, "test_logits", None)
        if not logits:
            return None
        probabilities = torch.softmax(torch.cat(logits).float(), dim=1).numpy()
        test_df = data_module.test_dataset.df
        if len(test_df) != len(probabilities):
            raise ValueError(
                f"Test metadata has {len(test_df)} rows but the model collected {len(probabilities)} logits."
            )

        rows = pd.DataFrame(
            {
                "source_index": test_df.index.to_numpy(),
                "fold": fold_num,
                "model_name": config.MODEL_NAME,
                "data_type": config.DATA_TYPE,
                "target": np.asarray(model.test_targets),
                "prediction": np.asarray(model.test_predictions),
            }
        )
        for class_index, class_name in enumerate(self.class_names):
            rows[f"prob_{class_name}"] = probabilities[:, class_index]
        hmi_preferred = pp_common.availability_mask(test_df, "path_image_cutout_hmi").to_numpy()
        rows["instrument"] = np.where(hmi_preferred, "HMI", "MDI")
        for column in ("number", "dates", "time", "label", "grouped_labels"):
            if column in test_df.columns:
                rows[column] = test_df[column].to_numpy()

        output_path = output_dir / "test_predictions.csv"
        rows.to_csv(output_path, index=False)
        return output_path

    def _save_delta_predictions(
        self,
        model: HaleLightningModel,
        data_module: HaleDataModule,
        fold_num: int,
        output_dir: Path,
    ) -> Path | None:
        """Save aligned held-out delta probabilities and routing outputs."""
        prediction_data = model.get_delta_prediction_data()
        if prediction_data is None:
            return None
        test_df = data_module.test_dataset.df
        if len(test_df) != len(prediction_data["delta_targets"]):
            raise ValueError(
                f"Test metadata has {len(test_df)} rows but the model collected "
                f"{len(prediction_data['delta_targets'])} delta outputs."
            )

        rows = pd.DataFrame(
            {
                "source_index": test_df.index.to_numpy(),
                "fold": fold_num,
                "model_name": config.MODEL_NAME,
                "data_type": config.DATA_TYPE,
                "base_target": prediction_data["base_targets"],
                "base_prediction": prediction_data["base_predictions"],
                "base_target_name": prediction_data["base_target_names"],
                "base_prediction_name": prediction_data["base_prediction_names"],
                "delta_target": prediction_data["delta_targets"],
                "delta_probability": prediction_data["delta_scores"],
                "delta_prediction": prediction_data["delta_predictions"],
                "delta_eligible_ground_truth": prediction_data["eligible_ground_truth"],
                "routed_true_label": prediction_data["routed_true_labels"],
                "routed_predicted_label": prediction_data["routed_predicted_labels"],
            }
        )
        metadata_columns = ("number", "dates", "time", "label", "grouped_labels")
        for column in metadata_columns:
            if column in test_df.columns:
                rows[column] = test_df[column].to_numpy()

        output_path = output_dir / "delta_predictions.csv"
        rows.to_csv(output_path, index=False)
        return output_path
